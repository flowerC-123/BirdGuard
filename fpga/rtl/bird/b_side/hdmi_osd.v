// Render status panels using a pipelined glyph ROM.
module hdmi_osd #(
    parameter WIDTH = 1280,
    HEIGHT = 720,
    MAX_HOLD_FRAMES = 120,
    PANEL_LAYOUT = 0,
    COLOR_LABELS = 0,
    VOLTAGE_REFERENCE = 0
) (
    input wire pixel_clk,
    rst_n,
    input wire [23:0] in_rgb,
    input wire in_de,
    in_hs,
    in_vs,
    input wire [11:0] in_x,
    in_y,
    input wire frame_start,
    input wire meta_valid,
    input wire [596:0] meta_payload,
    input wire [6:0] meta_cfg,
    output wire meta_take,
    output reg [23:0] out_rgb,
    output reg out_de,
    out_hs,
    out_vs,
    output wire [15:0] scene_age,
    output wire scene_fresh,
    output reg out_overlay
);

    reg [596:0] active;
    reg [  4:0] active_cfg;
    reg [  4:0] clean_cfg;
    always @* begin
        clean_cfg = 0;
        if (COLOR_LABELS)
            case (meta_cfg[4:0])
                5'd2, 5'd3, 5'd6, 5'd7, 5'd10, 5'd11, 5'd14, 5'd15, 5'd18, 5'd19, 5'd22, 5'd23:
                clean_cfg = meta_cfg[4:0];
                default: clean_cfg = 0;
            endcase
    end
    reg known;
    reg [15:0] age, heartbeat_age;
    wire info_fresh = known && heartbeat_age < MAX_HOLD_FRAMES;
    assign meta_take   = frame_start && !in_de && meta_valid;
    assign scene_age   = age;
    assign scene_fresh = known && age < MAX_HOLD_FRAMES;
    always @(posedge pixel_clk or negedge rst_n) begin
        if (!rst_n) begin
            active <= 0;
            active_cfg <= 0;
            known <= 0;
            age <= 16'hffff;
            heartbeat_age <= 16'hffff;
        end else if (frame_start && !in_de) begin
            if (meta_valid) begin
                active <= meta_payload;
                active_cfg <= clean_cfg;
                known <= 1;
                heartbeat_age <= 0;
                if (!known || active[575:512] != meta_payload[575:512]) age <= 0;
                else if (age != 16'hffff) age <= age + 1'b1;
            end else begin
                if (age != 16'hffff) age <= age + 1'b1;
                if (heartbeat_age != 16'hffff) heartbeat_age <= heartbeat_age + 1'b1;
            end
        end
    end

    wire [15:0] voltage = active[595:580];
    wire [ 3:0] sys_state = active[579:576];
    wire        volt_ok = info_fresh && active[596];
    wire [15:0] age_shown = (age > 16'd999) ? 16'd999 : age;

    localparam PANEL_MODE  = PANEL_LAYOUT != 0 && WIDTH >= 960 && HEIGHT >= 160;
    localparam PANEL_STEP  = (WIDTH - 32) / 4;
    localparam COLOR_PANEL = COLOR_LABELS && PANEL_MODE;
    localparam SLOT_SHIFT  = COLOR_PANEL ? 6 : 5, TABLE_AW = COLOR_PANEL ? 9 : 8;
    localparam ROW2_OFFSET = COLOR_PANEL ? 32 : 17;

    function [7:0] digit;
        input [15:0] value;
        input [2:0] pos;
        begin
            case (pos)
                0: digit = 48 + (value % 10);
                1: digit = 48 + ((value / 10) % 10);
                2: digit = 48 + ((value / 100) % 10);
                3: digit = 48 + ((value / 1000) % 10);
                4: digit = 48 + ((value / 10000) % 10);
                default: digit = 48;
            endcase
        end
    endfunction

    function [7:0] color_panel_labelch;
        input [2:0] label;
        input [6:0] confidence;
        input [4:0] char_index;
        input [1:0] slot;
        input [4:0] cfg;
        reg [47:0] name;
        reg [ 2:0] len;
        reg [ 4:0] shifted;
        begin
            name = 0;
            len  = 0;
            if (cfg[1:0] == 2 || cfg[1:0] == 3)
                case (cfg[4:2])
                    0: begin
                        name = "RED   ";
                        len  = 3;
                    end
                    1: begin
                        name = "GREEN ";
                        len  = 5;
                    end
                    2: begin
                        name = "BLUE  ";
                        len  = 4;
                    end
                    3: begin
                        name = "BRIGHT";
                        len  = 6;
                    end
                    4: begin
                        name = "DARK  ";
                        len  = 4;
                    end
                    5: begin
                        name = "CHROMA";
                        len  = 6;
                    end
                endcase
            color_panel_labelch = 32;
            shifted = char_index - (len == 0 ? 0 : len + 5'd1);
            if (char_index == 0) color_panel_labelch = 49 + slot;
            else if (len != 0 && char_index >= 2 && char_index < 2 + len)
                color_panel_labelch = name[47-(char_index-2)*8-:8];
            else if (char_index >= 2 + (len == 0 ? 0 : len + 5'd1) && shifted < 15) begin
                if (label == 0 && shifted >= 6)
                    case (shifted)
                        6: color_panel_labelch = "W";
                        7: color_panel_labelch = "A";
                        8: color_panel_labelch = "I";
                        9: color_panel_labelch = "T";
                    endcase
                else color_panel_labelch = panel_labelch(label, confidence, shifted[3:0], slot);
            end
        end
    endfunction

    function [7:0] panel_labelch;
        input [2:0] label;
        input [6:0] confidence;
        input [3:0] char_index;
        input [1:0] slot;
        begin
            panel_labelch = 32;
            if (char_index == 0) panel_labelch = 49 + slot;
            else if (char_index == 2) panel_labelch = 82;
            else if (char_index == 3) panel_labelch = 79;
            else if (char_index == 4) panel_labelch = 73;
            else if (char_index >= 6) begin
                case (label)
                    1:
                    case (char_index)
                        6:  panel_labelch = 66;
                        7:  panel_labelch = 73;
                        8:  panel_labelch = 82;
                        9:  panel_labelch = 68;
                        10: panel_labelch = confidence == 100 ? 49 : 32;
                        11: panel_labelch = digit(confidence, 1);
                        12: panel_labelch = digit(confidence, 0);
                        13: panel_labelch = 37;
                    endcase
                    2:
                    case (char_index)
                        6:  panel_labelch = 78;
                        7:  panel_labelch = 79;
                        9:  panel_labelch = 66;
                        10: panel_labelch = 73;
                        11: panel_labelch = 82;
                        12: panel_labelch = 68;
                    endcase
                    3: if (char_index < 10) panel_labelch = 138 + char_index - 6;
                    4: if (char_index < 10) panel_labelch = 142 + char_index - 6;
                    5: if (char_index < 10) panel_labelch = 146 + char_index - 6;
                    default: if (char_index < 12) panel_labelch = 132 + char_index - 6;
                endcase
            end
        end
    endfunction

    function [7:0] shapech;
        input [2:0] shape;
        input [2:0] char_index;
        begin
            shapech = 32;
            case (shape)
                3'd1:
                case (char_index)
                    0: shapech = 67;
                    1: shapech = 73;
                    2: shapech = 82;
                endcase
                3'd2:
                case (char_index)
                    0: shapech = 84;
                    1: shapech = 82;
                    2: shapech = 73;
                endcase
                3'd3:
                case (char_index)
                    0: shapech = 82;
                    1: shapech = 69;
                    2: shapech = 67;
                endcase
                default:
                case (char_index)
                    0: shapech = 85;
                    1: shapech = 78;
                    2: shapech = 75;
                endcase
            endcase
        end
    endfunction
    function [7:0] hexchar;
        input [3:0] nibble;
        begin
            hexchar = nibble < 10 ? 48 + nibble : 65 + nibble - 10;
        end
    endfunction

    function [7:0] labelch;
        input [2:0] label;
        input [6:0] confidence;
        input [3:0] char_index;
        begin
            labelch = 32;
            case (label)

                3'd1:
                case (char_index)
                    4'd0:  labelch = 82;
                    4'd1:  labelch = 79;
                    4'd2:  labelch = 73;
                    4'd4:  labelch = 66;
                    4'd5:  labelch = 73;
                    4'd6:  labelch = 82;
                    4'd7:  labelch = 68;
                    4'd8:  labelch = confidence == 100 ? 49 : 32;
                    4'd9:  labelch = digit(confidence, 3'd1);
                    4'd10: labelch = digit(confidence, 3'd0);
                    4'd11: labelch = 37;
                endcase
                3'd2:
                case (char_index)
                    4'd0:  labelch = 82;
                    4'd1:  labelch = 79;
                    4'd2:  labelch = 73;
                    4'd4:  labelch = 78;
                    4'd5:  labelch = 79;
                    4'd7:  labelch = 66;
                    4'd8:  labelch = 73;
                    4'd9:  labelch = 82;
                    4'd10: labelch = 68;
                endcase
                3'd3: if (char_index < 4'd4) labelch = 138 + char_index;
                3'd4: if (char_index < 4'd4) labelch = 142 + char_index;
                3'd5: if (char_index < 4'd4) labelch = 146 + char_index;
                default: if (char_index < 4'd6) labelch = 132 + char_index;
            endcase
        end
    endfunction
    function [7:0] statech;
        input [3:0] state;
        input [2:0] char_index;
        begin
            statech = 32;
            case (state)
                4'd0: statech = 150 + char_index;
                4'd1: statech = 154 + char_index;
                4'd2: statech = (char_index < 3'd2) ? 158 + char_index : 128 + char_index - 2;
                4'd3: statech = 160 + char_index;
                4'd4: statech = 164 + char_index;
                4'd15: statech = 63;
                default: statech = 142 + char_index;
            endcase
        end
    endfunction

    function [2:0] safe_label;
        input [2:0] label;
        input [6:0] confidence;
        begin
            safe_label = (label == 3'd1 && (confidence < 80 || confidence > 100)) ? 3'd0 : label;
        end
    endfunction

    localparam [TABLE_AW-1:0] SPACE_ADDR = COLOR_PANEL ? 303 : 175;
    localparam [TABLE_AW-1:0] TBL_LAST   = SPACE_ADDR;
    reg  [         7:0] chbuf                              [0:(1<<TABLE_AW)-1];

    reg                 fill_run;
    reg  [TABLE_AW-1:0] w_cnt;
    wire                fill_start = frame_start && !in_de;
    always @(posedge pixel_clk or negedge rst_n) begin
        if (!rst_n) begin
            fill_run <= 1'b0;
            w_cnt <= 8'd0;
        end else if (fill_start) begin
            fill_run <= 1'b1;
            w_cnt <= 8'd0;
        end else if (fill_run) begin
            w_cnt <= w_cnt + 8'd1;
            if (w_cnt >= TBL_LAST) fill_run <= 1'b0;
        end
    end

    reg [2:0] dlb0, dlb1, dlb2, dlb3;
    always @(posedge pixel_clk or negedge rst_n) begin
        if (!rst_n) begin
            dlb0 <= 3'd0;
            dlb1 <= 3'd0;
            dlb2 <= 3'd0;
            dlb3 <= 3'd0;
        end else if (fill_run && w_cnt == 8'd0) begin
            dlb0 <= safe_label(active[85+:3], active[88+:7]);
            dlb1 <= safe_label(active[213+:3], active[216+:7]);
            dlb2 <= safe_label(active[341+:3], active[344+:7]);
            dlb3 <= safe_label(active[469+:3], active[472+:7]);
        end
    end

    wire                f_hdr_l = (w_cnt < 8'd32);
    wire                f_hdr_r = (w_cnt >= 8'd32) && (w_cnt < 8'd48);
    wire [TABLE_AW-1:0] f_d = w_cnt - 48;
    wire [         1:0] f_bk = COLOR_PANEL ? f_d[7:6] : f_d[6:5];
    wire [         5:0] f_boff = COLOR_PANEL ? f_d[5:0] : {1'b0, f_d[4:0]};
    wire                f_row2 = (f_boff >= ROW2_OFFSET);
    wire [         4:0] f_bci = f_row2 ? (f_boff - ROW2_OFFSET) : f_boff;
    wire [         1:0] f_kind = f_hdr_l ? 2'd0 : (f_hdr_r ? 2'd1 : (f_row2 ? 2'd3 : 2'd2));
    wire [         4:0] f_ci = f_hdr_l ? w_cnt[4:0] : (f_hdr_r ? w_cnt[4:0] : f_bci);

    reg  [         1:0] s1_kind;
    reg  [         4:0] s1_ci;
    reg  [         1:0] s1_bk;
    reg  [TABLE_AW-1:0] s1_w;
    reg                 s1_we;
    always @(posedge pixel_clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_kind <= 0;
            s1_ci <= 0;
            s1_bk <= 0;
            s1_w <= 0;
            s1_we <= 1'b0;
        end else begin
            s1_kind <= f_kind;
            s1_ci <= f_ci;
            s1_bk <= f_bk;
            s1_w <= w_cnt;
            s1_we <= fill_run;
        end
    end

    reg [ 2:0] f_sel;
    reg [15:0] f_val;
    reg [ 4:0] f_pos;
    reg [ 7:0] f_cv;
    reg [ 9:0] f_base;
    always @* begin
        f_sel  = 3'd0;
        f_val  = 16'd0;
        f_pos  = 4'd0;
        f_cv   = 8'd32;
        f_base = {8'd0, s1_bk} << 7;
        case (s1_kind)

            2'd0: begin
                if (s1_ci <= 5'd5) begin
                    case (s1_ci)
                        5'd0: f_cv = 8'd83;
                        5'd1: f_cv = 8'd84;
                        5'd2: f_cv = 8'd65;
                        5'd3: f_cv = 8'd84;
                        5'd4: f_cv = 8'd69;
                        5'd5: f_cv = 8'd58;
                        default: f_cv = 8'd32;
                    endcase
                end else if (s1_ci <= 5'd9) begin
                    if (info_fresh) begin
                        f_sel = 3'd4;
                        f_val = {12'd0, sys_state};
                        f_pos = s1_ci - 5'd6;
                    end else f_cv = 8'd63;
                end else if (s1_ci >= 5'd11 && s1_ci <= 5'd14) begin
                    case (s1_ci)
                        5'd11:   f_cv = 8'd82;
                        5'd12:   f_cv = 8'd69;
                        5'd13:   f_cv = 8'd70;
                        5'd14:   f_cv = 8'd58;
                        default: f_cv = 8'd32;
                    endcase
                end else if (s1_ci >= 5'd15 && s1_ci <= 5'd22) begin
                    if (known) begin
                        f_sel = 3'd2;
                        f_val = {12'd0, active[512+((22-s1_ci)<<2)+:4]};
                    end else f_cv = 8'd45;
                end else if (s1_ci >= 5'd24 && s1_ci <= 5'd27) begin
                    case (s1_ci)
                        5'd24:   f_cv = 8'd65;
                        5'd25:   f_cv = 8'd71;
                        5'd26:   f_cv = 8'd69;
                        5'd27:   f_cv = 8'd58;
                        default: f_cv = 8'd32;
                    endcase
                end else if (s1_ci >= 5'd28 && s1_ci <= 5'd30) begin
                    if (known) begin
                        f_sel = 3'd1;
                        f_val = age_shown;
                        f_pos = 5'd30 - s1_ci;
                    end else f_cv = 8'd45;
                end
            end

            2'd1: begin

                if (VOLTAGE_REFERENCE) begin
                    case (s1_ci)
                        5'd0: f_cv = 8'd82;
                        5'd1: f_cv = 8'd69;
                        5'd2: f_cv = 8'd70;
                        5'd3: f_cv = 8'd58;
                        5'd4, 5'd5:
                        if (volt_ok) begin
                            f_sel = 3'd1;
                            f_val = voltage;
                            f_pos = 5'd7 - s1_ci;
                        end else f_cv = 8'd45;
                        5'd6: f_cv = 8'd46;
                        5'd7, 5'd8:
                        if (volt_ok) begin
                            f_sel = 3'd1;
                            f_val = voltage;
                            f_pos = 5'd8 - s1_ci;
                        end else f_cv = 8'd45;
                        5'd9: f_cv = 8'd86;
                        default: f_cv = 8'd32;
                    endcase
                end else begin
                    case (s1_ci)
                        5'd0: f_cv = 8'd86;
                        5'd1: f_cv = 8'd58;
                        5'd2, 5'd3, 5'd4:
                        if (volt_ok) begin
                            f_sel = 3'd1;
                            f_val = voltage;
                            f_pos = 5'd6 - s1_ci;
                        end else f_cv = 8'd45;
                        5'd5: f_cv = 8'd46;
                        5'd6, 5'd7:
                        if (volt_ok) begin
                            f_sel = 3'd1;
                            f_val = voltage;
                            f_pos = 5'd7 - s1_ci;
                        end else f_cv = 8'd45;
                        5'd8: f_cv = 8'd86;
                        default: f_cv = 8'd32;
                    endcase
                end
            end

            2'd2: begin
                case (s1_ci)
                    5'd0: f_cv = 8'd88;
                    5'd1: f_cv = 8'd58;
                    5'd2, 5'd3, 5'd4, 5'd5: begin
                        f_sel = 3'd1;
                        f_val = {4'd0, active[f_base+10'd1+:12]};
                        f_pos = 5'd5 - s1_ci;
                    end
                    5'd7: f_cv = 8'd89;
                    5'd8: f_cv = 8'd58;
                    5'd9, 5'd10, 5'd11: begin
                        f_sel = 3'd1;
                        f_val = {4'd0, active[f_base+10'd13+:12]};
                        f_pos = 5'd11 - s1_ci;
                    end
                    5'd13, 5'd14, 5'd15: begin
                        f_sel = 3'd5;
                        f_cv  = {5'd0, active[f_base+10'd82+:3]};
                        f_pos = s1_ci - 5'd13;
                    end
                    default: f_cv = 8'd32;
                endcase
            end

            default: begin
                if (s1_ci > (COLOR_PANEL ? 5'd20 : PANEL_MODE ? 5'd14 : 5'd11)) f_cv = 8'd32;
                else begin
                    f_sel = 3'd3;
                    f_val = {9'd0, active[f_base+10'd88+:7]};
                    f_cv = {
                        3'd0, s1_bk, safe_label(active[f_base+10'd85+:3], active[f_base+10'd88+:7])
                    };
                    f_pos = s1_ci;
                end
            end
        endcase
    end

    reg [2:0] s2_sel;
    reg [15:0] s2_val;
    reg [4:0] s2_pos;
    reg [7:0] s2_cv;
    reg [TABLE_AW-1:0] s2_w;
    reg s2_we;
    always @(posedge pixel_clk or negedge rst_n) begin
        if (!rst_n) begin
            s2_sel <= 0;
            s2_val <= 0;
            s2_pos <= 0;
            s2_cv  <= 0;
            s2_w   <= 0;
            s2_we  <= 1'b0;
        end else begin
            s2_sel <= f_sel;
            s2_val <= f_val;
            s2_pos <= f_pos;
            s2_cv  <= f_cv;
            s2_w   <= s1_w;
            s2_we  <= s1_we;
        end
    end

    reg [7:0] s3_val;
    always @* begin
        case (s2_sel)
            3'd1: s3_val = digit(s2_val, s2_pos[2:0]);
            3'd2: s3_val = hexchar(s2_val[3:0]);
            3'd3:
            s3_val = COLOR_PANEL ?
                color_panel_labelch(s2_cv[2:0], s2_val[6:0], s2_pos, s2_cv[4:3], active_cfg) :
                PANEL_MODE ? panel_labelch(s2_cv[2:0], s2_val[6:0], s2_pos[3:0], s2_cv[4:3]) :
                labelch(s2_cv[2:0], s2_val[6:0], s2_pos[3:0]);
            3'd4: s3_val = statech(s2_val[3:0], s2_pos[2:0]);
            3'd5: s3_val = shapech(s2_cv[2:0], s2_pos[2:0]);
            default: s3_val = s2_cv;
        endcase
    end

    always @(posedge pixel_clk) begin
        if (s2_we) chbuf[s2_w] <= s3_val;
    end

    function [11:0] clamp_lx;
        input [11:0] x0;
        begin
            clamp_lx = (x0 > WIDTH - 176) ? (WIDTH - 176) : x0;
        end
    endfunction
    function [11:0] clamp_ly;
        input [11:0] y0;
        reg [11:0] t;
        begin
            t = (y0 >= 36) ? (y0 - 34) : (y0 + 2);
            clamp_ly = (t > HEIGHT - 32) ? (HEIGHT - 32) : t;
        end
    endfunction

    function [11:0] live_label_y;
        input [11:0] y0;
        input [2:0] label;
        reg [11:0] t;
        begin
            if (label == 1 || label == 2) begin
                t = y0 + 12'd2;
                if (t < 12'd38) t = 12'd38;
                live_label_y = t > HEIGHT - 32 ? HEIGHT - 32 : t;
            end else live_label_y = clamp_ly(y0);
        end
    endfunction

    wire [11:0] s0x0 = active[1+:12], s0y0 = active[13+:12];
    wire [11:0] s0x1 = active[25+:12], s0y1 = active[37+:12];
    wire [11:0] s1x0 = active[129+:12], s1y0 = active[141+:12];
    wire [11:0] s1x1 = active[153+:12], s1y1 = active[165+:12];
    wire [11:0] s2x0 = active[257+:12], s2y0 = active[269+:12];
    wire [11:0] s2x1 = active[281+:12], s2y1 = active[293+:12];
    wire [11:0] s3x0 = active[385+:12], s3y0 = active[397+:12];
    wire [11:0] s3x1 = active[409+:12], s3y1 = active[421+:12];

    wire g_ok0 = active[0]   && scene_fresh && s0x0<=s0x1 && s0y0<=s0y1 && s0x1<WIDTH  && s0y1<HEIGHT;
    wire g_ok1 = active[128] && scene_fresh && s1x0<=s1x1 && s1y0<=s1y1 && s1x1<WIDTH  && s1y1<HEIGHT;
    wire g_ok2 = active[256] && scene_fresh && s2x0<=s2x1 && s2y0<=s2y1 && s2x1<WIDTH  && s2y1<HEIGHT;
    wire g_ok3 = active[384] && scene_fresh && s3x0<=s3x1 && s3y0<=s3y1 && s3x1<WIDTH  && s3y1<HEIGHT;

    wire [11:0] lx0 = PANEL_MODE ? 16 : clamp_lx(
        s0x0
    ), ly0 = PANEL_MODE ? 32 : live_label_y(
        s0y0, dlb0
    );
    wire [11:0] lx1 = PANEL_MODE ? 16 + PANEL_STEP : clamp_lx(
        s1x0
    ), ly1 = PANEL_MODE ? 32 : live_label_y(
        s1y0, dlb1
    );
    wire [11:0] lx2 = PANEL_MODE ? 16 + 2 * PANEL_STEP : clamp_lx(
        s2x0
    ), ly2 = PANEL_MODE ? 32 : live_label_y(
        s2y0, dlb2
    );
    wire [11:0] lx3 = PANEL_MODE ? 16 + 3 * PANEL_STEP : clamp_lx(
        s3x0
    ), ly3 = PANEL_MODE ? 32 : live_label_y(
        s3y0, dlb3
    );

    function [11:0] badge_y;
        input [11:0] y0;
        begin
            badge_y = y0 < 68 ? 68 : y0 > HEIGHT - 120 ? HEIGHT - 120 : y0;
        end
    endfunction
    wire [11:0] mx0 = s0x0 > WIDTH - 8 ? WIDTH - 8 : s0x0, my0 = badge_y(s0y0);

    wire [11:0] mx1 = s1x1 >= 7 ? s1x1 - 7 : 0, my1 = badge_y(s1y0);
    wire [11:0] mx2 = s2x0 > WIDTH - 8 ? WIDTH - 8 : s2x0, my2 = badge_y(
